package de.behindtheblocks.skinstudio.client.gui.ui;

import net.minecraft.client.gui.GuiGraphicsExtractor;

/** 7×7 pixel icons drawn with fills, so they stay crisp and take the theme color. */
public enum Icon {
	STAR("...#...", "..###..", "#######", ".#####.", "..###..", ".##.##.", ".#...#."),
	STAR_FILLED("...#...", "..###..", "#######", ".#####.", "..###..", ".##.##.", ".#...#."),
	CLOSE("#.....#", ".#...#.", "..#.#..", "...#...", "..#.#..", ".#...#.", "#.....#"),
	CHECK("......#", ".....#.", "#...#..", ".#.#...", "..#....", ".......", "......."),
	SEARCH(".###...", "#...#..", "#...#..", "#...#..", ".###...", "....##.", ".....##"),
	PLUS("...#...", "...#...", "...#...", "#######", "...#...", "...#...", "...#..."),
	EDIT(".....#.", "....###", "...###.", "..###..", ".###...", "##.....", "###...."),
	TRASH("..###..", "#######", ".#.#.#.", ".#.#.#.", ".#.#.#.", ".#.#.#.", ".#####."),
	BOX("..###..", ".#...#.", "#######", "#.....#", "#..#..#", "#.....#", "#######"),
	IMPORT("...#...", "...#...", ".#.#.#.", "..###..", "...#...", "#.....#", "#######"),
	EXPORT("...#...", "..###..", ".#.#.#.", "...#...", "...#...", "#.....#", "#######"),
	GEAR("..#.#..", ".#####.", "##...##", ".#...#.", "##...##", ".#####.", "..#.#.."),
	SUN("#..#..#", ".#...#.", "..###..", "#.###.#", "..###..", ".#...#.", "#..#..#"),
	MOON("..###..", ".##....", "##.....", "##.....", "##.....", ".##....", "..###.."),
	BACK("...#...", "..#....", ".#.....", "#######", ".#.....", "..#....", "...#..."),
	EYE(".......", "..###..", ".#...#.", "#..#..#", ".#...#.", "..###..", "......."),
	CLOCK("..###..", ".#.#.#.", "#..#..#", "#..##.#", "#.....#", ".#...#.", "..###.."),
	HANGER("...##..", "....#..", "...#...", "..#.#..", ".#...#.", "#.....#", "#######"),
	PALETTE("..###..", ".#.#.#.", "#.....#", "#.#...#", "#...###", ".#..#..", "..##..."),
	FOLDER("###....", "#######", "#.....#", "#.....#", "#.....#", "#.....#", "#######"),
	REFRESH("..####.", ".#...##", "#...###", "#......", "#.....#", ".#...#.", "..###.."),
	SAVE("######.", "#.#..##", "#.#..#.", "#######", "#.....#", "#.###.#", "#######"),
	LAYERS("...#...", "..#.#..", ".#...#.", "#.#.#.#", ".#.#.#.", "..#.#..", "...#..."),
	INFO("..###..", ".#.#.#.", "#.....#", "#..#..#", "#..#..#", ".#.#.#.", "..###.."),
	PLAY("#......", "###....", "#####..", "#######", "#####..", "###....", "#......");

	private final String[] rows;

	Icon(String... rows) {
		this.rows = rows;
	}

	public void draw(GuiGraphicsExtractor g, int x, int y, int color) {
		String[] r = rows;
		if (this == STAR) {
			// outline only
			for (int j = 0; j < r.length; j++) {
				for (int i = 0; i < r[j].length(); i++) {
					if (r[j].charAt(i) == '#' && isEdge(r, i, j)) {
						g.fill(x + i, y + j, x + i + 1, y + j + 1, color);
					}
				}
			}
			return;
		}
		for (int j = 0; j < r.length; j++) {
			String row = r[j];
			for (int i = 0; i < row.length(); i++) {
				if (row.charAt(i) == '#') {
					g.fill(x + i, y + j, x + i + 1, y + j + 1, color);
				}
			}
		}
	}

	private static boolean isEdge(String[] r, int i, int j) {
		int[][] d = {{1, 0}, {-1, 0}, {0, 1}, {0, -1}};
		for (int[] o : d) {
			int ni = i + o[0], nj = j + o[1];
			if (nj < 0 || nj >= r.length || ni < 0 || ni >= r[nj].length() || r[nj].charAt(ni) != '#') {
				return true;
			}
		}
		return false;
	}
}
